"""Writes archie_version.h: the running version and where to look for newer
ones (see archie_update_checker.cc). Run by prepare.sh / prepare.bat.

Usage: write_version_header.py SRC_DIR [UPDATE_REPO]
"""

import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = 'chrome/browser/ui/views/tabs/vertical/archie_version.h'


def main(argv):
  if not argv:
    sys.exit(__doc__)
  src = pathlib.Path(argv[0])
  version = (ROOT / 'ARCHIE_VERSION').read_text().strip()
  repo = argv[1] if len(argv) > 1 else os.environ.get(
      'ARCHIE_UPDATE_REPO', 'nicklitvin/archie')
  if not re.fullmatch(r'[0-9]+(\.[0-9]+)*', version):
    sys.exit("ARCHIE_VERSION must look like 1.2.3, got '%s'" % version)
  if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repo):
    sys.exit("ARCHIE_UPDATE_REPO must look like owner/repo, got '%s'" % repo)
  (src / HEADER).write_text(
      '// Generated by Archie\'s scripts/write_version_header.py from\n'
      '// ARCHIE_VERSION. Do not edit.\n\n'
      '#ifndef CHROME_BROWSER_UI_VIEWS_TABS_VERTICAL_ARCHIE_VERSION_H_\n'
      '#define CHROME_BROWSER_UI_VIEWS_TABS_VERTICAL_ARCHIE_VERSION_H_\n\n'
      'inline constexpr char kArchieVersion[] = "%s";\n'
      'inline constexpr char kArchieUpdateRepo[] = "%s";\n\n'
      '#endif  // CHROME_BROWSER_UI_VIEWS_TABS_VERTICAL_ARCHIE_VERSION_H_\n'
      % (version, repo), newline='\n')
  print('Archie %s, update checks against github.com/%s' % (version, repo))


if __name__ == '__main__':
  main(sys.argv[1:])
