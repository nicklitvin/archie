"""Converts Lucide SVG icons into Chromium .icon vector files.

Lucide icons are 24x24 outlines drawn with a 2px stroke, round caps and round
joins. Chromium's .icon format can stroke paths but only with mitered joins,
so instead each stroke is expanded into a filled outline with picosvg (which
uses Skia's own path ops) and written as fill commands. The result renders
exactly like Lucide at any size and takes its colour from the button.

Usage: lucide_to_icon.py OUT_DIR icon.svg [icon.svg ...]
Writes OUT_DIR/lucide_<name>.icon, available in C++ as
vector_icons::kLucide<Name>Icon once listed in components/vector_icons/BUILD.gn.
Needs `pip install picosvg`.
"""

import pathlib
import re
import sys

from picosvg.svg import SVG

HEADER = """// Copyright 2026 The Archie Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.
//
// Generated by scripts/lucide_to_icon.py from Lucide's "{name}" icon
// (https://lucide.dev, ISC license). Do not edit.

CANVAS_DIMENSIONS, 24,
"""

# Commands picosvg emits, and the .icon command with its argument count.
COMMANDS = {'M': ('MOVE_TO', 2), 'L': ('LINE_TO', 2), 'Q': ('QUADRATIC_TO', 4),
            'C': ('CUBIC_TO', 6), 'Z': ('CLOSE', 0)}


def number(value):
  value = round(float(value), 3)
  if value == int(value):
    return str(int(value))
  return ('%.3f' % value).rstrip('0') + 'f'


def path_commands(d):
  tokens = re.findall(r'[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?', d)
  lines, i = [], 0
  while i < len(tokens):
    letter = tokens[i]
    if letter not in COMMANDS:
      raise ValueError('unsupported path command %r' % letter)
    name, count = COMMANDS[letter]
    args = tokens[i + 1:i + 1 + count]
    lines.append(', '.join([name] + [number(a) for a in args]) + ',')
    i += 1 + count
  return lines


def convert(svg_path):
  name = svg_path.stem
  picture = SVG.parse(str(svg_path)).topicosvg()
  paths = [el.attrib['d'] for el in picture.svg_root.iter()
           if el.tag.endswith('path') and el.attrib.get('d')]
  body = []
  for index, d in enumerate(paths):
    if index:
      body.append('NEW_PATH,')
    body += path_commands(d)
  return name, HEADER.format(name=name) + '\n'.join(body) + '\n'


def main(argv):
  if len(argv) < 2:
    sys.exit(__doc__)
  out_dir = pathlib.Path(argv[0])
  out_dir.mkdir(parents=True, exist_ok=True)
  for svg in argv[1:]:
    name, text = convert(pathlib.Path(svg))
    out = out_dir / ('lucide_%s.icon' % name.replace('-', '_'))
    out.write_text(text)
    print('wrote', out)


if __name__ == '__main__':
  main(sys.argv[1:])
