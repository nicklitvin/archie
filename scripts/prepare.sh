#!/usr/bin/env bash
# Turns a Chromium checkout into Archie: applies patches/series, installs the
# branding and renames the product in UI strings. Safe to re-run.
#   --reset   discard all local changes in the checkout first
source "$(dirname "$0")/common.sh"

[[ -d "$SRC/.git" ]] || die "No Chromium checkout at $SRC. Run scripts/fetch.sh first."

if [[ "${1:-}" == --reset ]]; then
  log "Resetting $SRC to a clean $CHROMIUM_VERSION"
  git -C "$SRC" reset --hard --quiet
  git -C "$SRC" clean -fdq
fi

while read -r patch; do
  name="${patch#"$ARCHIE_ROOT"/patches/}"
  if git -C "$SRC" apply --reverse --check "$patch" 2>/dev/null; then
    log "already applied: $name"
  else
    git -C "$SRC" apply "$patch" || die "failed to apply $name (try --reset)"
    log "applied: $name"
  fi
done < <(series)

cp "$ARCHIE_ROOT/branding/BRANDING" "$SRC/chrome/app/theme/chromium/BRANDING"
log "installed branding"

python3 "$ARCHIE_ROOT/scripts/rebrand.py" "$SRC"

# The running version and where to look for newer ones (see
# archie_update_checker.cc). Regenerated every time so it is never stale.
[[ "$ARCHIE_VERSION" =~ ^[0-9]+(\.[0-9]+)*$ ]] ||
  die "ARCHIE_VERSION must look like 1.2.3, got '$ARCHIE_VERSION'"
[[ "$ARCHIE_UPDATE_REPO" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] ||
  die "ARCHIE_UPDATE_REPO must look like owner/repo, got '$ARCHIE_UPDATE_REPO'"
cat > "$SRC/chrome/browser/ui/views/tabs/vertical/archie_version.h" <<HEADER
// Generated by Archie's scripts/prepare.sh from ARCHIE_VERSION. Do not edit.

#ifndef CHROME_BROWSER_UI_VIEWS_TABS_VERTICAL_ARCHIE_VERSION_H_
#define CHROME_BROWSER_UI_VIEWS_TABS_VERTICAL_ARCHIE_VERSION_H_

inline constexpr char kArchieVersion[] = "$ARCHIE_VERSION";
inline constexpr char kArchieUpdateRepo[] = "$ARCHIE_UPDATE_REPO";

#endif  // CHROME_BROWSER_UI_VIEWS_TABS_VERTICAL_ARCHIE_VERSION_H_
HEADER
log "Archie $ARCHIE_VERSION, update checks against github.com/$ARCHIE_UPDATE_REPO"
log "Done. Next: scripts/build.sh"
